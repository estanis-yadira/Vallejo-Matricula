    private void configurarMenu() {
        menu.put("dashboard", btnDashboard);
        menu.put("estudiantes", btnEstudiantes);
        menu.put("docentes", btnDocentes);
        menu.put("salones", btnSalones);
        menu.put("cursos", btnCursos);
        menu.put("horarios", btnHorarios);
        menu.put("matriculas", btnMatricula);
        menu.put("reportes", btnReportes);
        menu.put("cerrarSesion", btnCerrarSesion);

        for (JButton boton : menu.values()) {
            // Evita el destello gris al hacer clic
            boton.setUI(new javax.swing.plaf.basic.BasicButtonUI() {
                @Override
                protected void paintButtonPressed(java.awt.Graphics g, javax.swing.AbstractButton b) {
                    // vacío a propósito: no se pinta el color de "presionado"
                }
            });

            boton.setBorder(BORDE_NORMAL);
            boton.setOpaque(true);
            boton.setBackground(COLOR_NORMAL);
            boton.setContentAreaFilled(true);

            boton.addMouseListener(new MouseAdapter() {
                @Override
                public void mouseEntered(MouseEvent e) {
                    if (boton != botonActivo) {
                        pintar(boton, COLOR_HOVER);
                    }
                }

                @Override
                public void mouseExited(MouseEvent e) {
                    if (boton != botonActivo) {
                        pintar(boton, COLOR_NORMAL);
                    }
                }
            });
        }
        marcarActivo("dashboard");
    }

    private void pintar(JButton boton, Color color) {
        boton.setBackground(color);
    }

    private void marcarActivo(String nombrePanel) {
        JButton nuevo = menu.get(nombrePanel);
        if (nuevo == null) {
            return;
        }

        if (botonActivo != null) {
            pintar(botonActivo, COLOR_NORMAL);
            botonActivo.setBorder(BORDE_NORMAL);
        }

        botonActivo = nuevo;
        pintar(nuevo, COLOR_ACTIVO);
        nuevo.setBorder(BORDE_ACTIVO);
    }

